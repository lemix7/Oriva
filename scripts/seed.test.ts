import assert from "node:assert/strict";
import { after, before, beforeEach, describe, test } from "node:test";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import dotenv from "dotenv";
import pg from "pg";
import bcrypt from "bcryptjs";
import { drizzle, type NodePgDatabase } from "drizzle-orm/node-postgres";
import { eq } from "drizzle-orm";
import { projects, tasks, users } from "../src/db/schema.ts";
import { seedDatabaseUrl, seedDemo } from "./seed.ts";

test("seed URL accepts loopback hosts and always targets the migration demo database", () => {
  for (const host of ["localhost", "127.0.0.1", "[::1]"]) {
    const url = new URL(seedDatabaseUrl(`postgresql://demo@${host}:5432/oriva_test`));
    assert.equal(url.hostname, host);
    assert.equal(url.pathname, "/oriva_migration_test");
  }
});

test("seed URL rejects a missing connection, remote hosts, and host overrides", () => {
  assert.throws(() => seedDatabaseUrl(undefined));
  for (const url of [
    "postgresql://demo@example.com/oriva_test",
    "https://localhost/oriva_test",
    "postgresql://demo@localhost/oriva_test?host=example.com",
    "postgresql://demo@localhost/oriva_test?hostaddr=192.0.2.1",
  ]) {
    assert.throws(() => seedDatabaseUrl(url), /Seeding requires local PostgreSQL/);
  }
});

test("the command exits unsuccessfully without printing connection credentials", () => {
  const result = spawnSync(process.execPath, ["--import", "tsx", "scripts/seed.ts"], {
    env: {
      ...process.env,
      TEST_DATABASE_URL: "postgresql://demo:test-only-secret@example.com/oriva_test",
    },
    encoding: "utf8",
    timeout: 5000,
  });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /Local demo seed failed/);
  assert.doesNotMatch(result.stdout + result.stderr, /test-only-secret|postgresql:\/\//);
});

describe("seed behavior on isolated temporary tables", () => {
  let client: pg.Client;
  let db: NodePgDatabase;

  before(async () => {
    const config = dotenv.parse(readFileSync(".env.test"));
    const url = new URL(process.env.TEST_DATABASE_URL || config.TEST_DATABASE_URL);
    if (
      !["localhost", "127.0.0.1", "[::1]"].includes(url.hostname) ||
      url.pathname !== "/oriva_test" || url.searchParams.has("host") ||
      url.searchParams.has("hostaddr")
    ) {
      throw new Error("Seed tests require the local oriva_test database");
    }
    client = new pg.Client({ connectionString: url.href, connectionTimeoutMillis: 5000 });
    await client.connect();
    // Temp tables shadow the real tables only on this connection. Their identity
    // sequences are private too, so the tests don't consume application IDs.
    for (const name of ["users", "projects", "tasks"]) {
      await client.query(`CREATE TEMP TABLE ${name} (LIKE public.${name} INCLUDING DEFAULTS INCLUDING CONSTRAINTS)`);
      await client.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id DROP DEFAULT`);
      await client.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
      await client.query(`ALTER TABLE pg_temp.${name} ADD PRIMARY KEY (id)`);
    }
    await client.query("ALTER TABLE pg_temp.projects ADD FOREIGN KEY (user_id) REFERENCES pg_temp.users(id)");
    await client.query("ALTER TABLE pg_temp.tasks ADD FOREIGN KEY (project_id) REFERENCES pg_temp.projects(id)");
    db = drizzle({ client });
  });

  beforeEach(async () => {
    await client.query("TRUNCATE pg_temp.tasks, pg_temp.projects, pg_temp.users RESTART IDENTITY");
  });

  after(async () => { await client?.end(); });

  test("two runs create one hashed-password owner, one project, and two linked tasks", async () => {
    await seedDemo(db);
    const first = {
      users: await db.select().from(users),
      projects: await db.select().from(projects),
      tasks: await db.select().from(tasks).orderBy(tasks.id),
    };
    await seedDemo(db);
    const second = {
      users: await db.select().from(users),
      projects: await db.select().from(projects),
      tasks: await db.select().from(tasks).orderBy(tasks.id),
    };
    assert.deepEqual(second, first);
    assert.equal(second.users.length, 1);
    assert.equal(second.projects.length, 1);
    assert.equal(second.tasks.length, 2);
    assert.notEqual(second.users[0].password, "LocalDemo123!");
    assert.equal(await bcrypt.compare("LocalDemo123!", second.users[0].password), true);
    assert.equal(second.projects[0].userId, second.users[0].id);
    assert.equal(second.projects[0].createdAt?.toISOString(), "2026-01-01T00:00:00.000Z");
    assert.deepEqual(second.tasks.map(task => task.status).sort(), ["done", "on progress"]);
    assert.ok(second.tasks.every(task => task.projectId === second.projects[0].id));
  });

  test("reruns preserve edits and recreate a missing demo task", async () => {
    await seedDemo(db);
    await db.update(projects).set({ description: "My local edit" });
    await db.update(tasks).set({ status: "cancelled" }).where(eq(tasks.title, "Plan the project"));
    await db.delete(tasks).where(eq(tasks.title, "Build the first feature"));
    await seedDemo(db);
    const [project] = await db.select().from(projects);
    const rows = await db.select().from(tasks);
    assert.equal(project.description, "My local edit");
    assert.equal(rows.length, 2);
    assert.equal(rows.find(task => task.title === "Plan the project")?.status, "cancelled");
    assert.equal(rows.find(task => task.title === "Build the first feature")?.status, "on progress");
  });

  test("a task failure rolls back the owner, project, and earlier task", async () => {
    await client.query("ALTER TABLE pg_temp.tasks ADD CONSTRAINT seed_forced_failure CHECK (title <> 'Build the first feature')");
    try {
      await assert.rejects(() => seedDemo(db));
      assert.equal((await db.select().from(users)).length, 0);
      assert.equal((await db.select().from(projects)).length, 0);
      assert.equal((await db.select().from(tasks)).length, 0);
    } finally {
      await client.query("ALTER TABLE pg_temp.tasks DROP CONSTRAINT seed_forced_failure");
    }
  });
});
